import { type CraftingStation, type ItemSource, MATERIALS_GROUP, type Recipe, type RecipeBiome, type RecipeKind } from '#/lib/models/recipes';

/**
 * One building piece or gathered material. [ingredients] maps each item to what one piece takes.
 * A gathered material has no ingredients: the plan tracks that material itself, the same way a
 * crafted recipe tracks the items it takes.
 */
const piece = (
  id: string,
  name: string,
  biome: RecipeBiome,
  station: CraftingStation,
  ingredients: Record<string, number>,
  kind: RecipeKind = 'build',
  group?: string,
  sources: ItemSource[] = [],
): Recipe => ({
  id,
  name,
  biome,
  station,
  yields: 1,
  kind,
  ingredients: Object.entries(ingredients).map(([item, amount]) => ({ item, amount })),
  ...(group === undefined ? {} : { group }),
  ...(sources.length === 0 ? {} : { sources }),
});

/** One place a material comes from: its name, how many one of them gives, and the icon to show. */
const from = (name: string, amount: number, iconItem: string): ItemSource => ({ name, amount, iconItem });

/**
 * A material you pick up or chop, shown ahead of the pieces. Tree counts are one full tree at the
 * normal resource rate: what its logs drop, plus the 2 its stump drops (ashwood, on a scorched tree).
 * A pine's 30 log drops split evenly, so 15 wood and 15 core wood is the usual tree, and the stump
 * adds 2 more wood. A mined rock drops 1 stone, once or twice. A petrified bone drops 2 to 4 black
 * marble. A large grausten outcrop rolls 4 to 8 times and about 5 of those are grausten.
 */
const gathered = (id: string, name: string, biome: RecipeBiome, sources: ItemSource[]): Recipe =>
  piece(id, name, biome, 'Hand', {}, 'gather', MATERIALS_GROUP, sources);

