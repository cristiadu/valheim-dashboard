/** Returns the address of [item]'s game sprite, or undefined when the wiki is the only source. */
export const gameIconUrl = (item: string): string | undefined => {
  const path = GAME_ICON_FILES[item];
  return path === undefined ? undefined : `${GAME_ICON_BASE}${path}`;
};
