import type { CraftingStation, Recipe, RecipeBiome } from '#/lib/models/recipes';

/** One crafting station. [ingredients] maps each item to what placing one takes. */
const station = (
  id: string,
  name: string,
  biome: RecipeBiome,
  nearby: CraftingStation,
  ingredients: Record<string, number>,
): Recipe => ({
  id,
  name,
  biome,
  station: nearby,
  yields: 1,
  kind: 'station',
  ingredients: Object.entries(ingredients).map(([item, amount]) => ({ item, amount })),
});

